"""Profile the S-Pankki CSVs in data/ and write DATA.md.

Usage:
    python scripts/profile_data.py

Reads the local CSVs (see SETUP.md for how to download them), not the shared
database, so it never loads Aiven. Takes about a minute.
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
OUT = ROOT / "DATA.md"

# Merchant category codes (ISO 18245) that appear in the dataset.
MCC_LABELS = {
    "4111": "Local commuter transport", "4121": "Taxis", "4511": "Airlines",
    "4722": "Travel agencies", "5200": "Home supply warehouses", "5251": "Hardware stores",
    "5411": "Grocery stores, supermarkets", "5422": "Meat provisioners", "5451": "Dairy stores",
    "5499": "Convenience / specialty food", "5541": "Service stations", "5542": "Automated fuel dispensers",
    "5651": "Family clothing", "5691": "Clothing stores", "5712": "Furniture stores",
    "5732": "Electronics stores", "5734": "Computer software stores", "5812": "Restaurants",
    "5813": "Bars, pubs", "5814": "Fast food, cafés", "5912": "Pharmacies", "5941": "Sporting goods",
    "5942": "Book stores", "5945": "Hobby, toy and game shops", "5999": "Miscellaneous retail",
    "7011": "Hotels", "7512": "Car rental", "7523": "Parking", "7832": "Cinemas",
    "7922": "Theatre / event tickets", "7991": "Tourist attractions", "7996": "Amusement parks",
    "7999": "Recreation services", "8011": "Doctors", "8021": "Dentists", "8099": "Medical services",
}


def eur(x):
    return f"{x:,.0f} €".replace(",", " ")


def eur2(x):
    return f"{x:,.2f} €".replace(",", " ")


def num(x):
    return f"{x:,}".replace(",", " ")


def pct(x):
    return f"{x:.1f}%"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def read(name, **kw):
    return pd.read_csv(DATA_DIR / name, encoding="utf-8-sig", **kw)


def main():
    tx = read("tx_junction_transactions.csv",
              dtype={"customer_id": "category", "bank_account_id": "category", "category": "category",
                     "transaction_type": "category", "merchant_id": "string", "mcc_code": "string"},
              parse_dates=["tx_date"])
    tx["tx_timestamp"] = pd.to_datetime(tx["tx_timestamp"], format="%d%b%y:%H:%M:%S")
    customers = read("tx_customers_junction.csv", dtype={"customer_id": "string", "customer_postal_code": "string"})
    events = read("mtg_negotiation_history.csv", dtype={"mortgage_customer_id": "string", "property_id": "string"})
    outcomes = read("mtg_tx_customer_link_and_final_mtg_infio.csv", dtype={"mortgage_customer_id": "string"})

    n_tx, n_cust = len(tx), tx["customer_id"].nunique()
    first, last = tx["tx_date"].min(), tx["tx_date"].max()
    n_months = (last.year - first.year) * 12 + last.month - first.month + 1
    tx["month"] = tx["tx_date"].dt.to_period("M")
    out = []
    w = out.append

    w("# Data profile\n")
    w("Generated by `scripts/profile_data.py` from the S-Pankki CSVs in `data/`. Re-run it to refresh. "
      "Field meanings are in [CHALLENGE.md](CHALLENGE.md#summary-brief-s-pankki-pdf); how we load the data is in "
      "[SETUP.md](SETUP.md).\n")
    w("Amounts: negative = money out, positive = money in. \"Spent\" columns show money out as a positive number.\n")

    # ---- overview -----------------------------------------------------------
    w("## Overview\n")
    w(table(["", ""], [
        ["Transactions", num(n_tx)],
        ["Customers", f"{num(n_cust)} (each has exactly {tx.groupby('customer_id', observed=True)['bank_account_id'].nunique().max()} account)"],
        ["Date range", f"{first.date()} – {last.date()} ({n_months} months)"],
        ["Transactions per customer", f"median {tx.groupby('customer_id', observed=True).size().median():.0f}, "
                                      f"min {tx.groupby('customer_id', observed=True).size().min()}, "
                                      f"max {tx.groupby('customer_id', observed=True).size().max()}"],
        ["Money in (positive amounts)", f"{num(int((tx.tx_amount_eur > 0).sum()))} rows"],
        ["Money out (negative amounts)", f"{num(int((tx.tx_amount_eur < 0).sum()))} rows"],
        ["Zero amounts", num(int((tx.tx_amount_eur == 0).sum()))],
    ]))
    w("")

    # ---- columns ------------------------------------------------------------
    w("## Columns\n")
    rows = []
    for col in ["customer_id", "bank_account_id", "tx_date", "tx_timestamp", "category", "tx_amount_eur",
                "balance_after_eur", "transaction_type", "merchant_id", "mcc_code"]:
        s = tx[col]
        rows.append([f"`{col}`", num(int(s.nunique())), num(int(s.isna().sum())),
                     pct(s.isna().mean() * 100)])
    w(table(["Column", "Unique values", "Empty", "Empty %"], rows))
    w("\n`merchant_id` and `mcc_code` are empty exactly for non-card payments (transfers, bills, salary).\n")

    # ---- categories ---------------------------------------------------------
    w("## Categories\n")
    g = tx.groupby("category", observed=True)
    cust_share = g["customer_id"].nunique() / n_cust * 100
    rows = []
    for cat, s in g:
        amt = s["tx_amount_eur"]
        types = ", ".join(f"`{t}`" for t in s["transaction_type"].unique())
        direction = "out" if (amt < 0).all() else "in" if (amt > 0).all() else "mixed"
        per_cust_month = len(s) / s["customer_id"].nunique() / n_months
        rows.append([f"**{cat}**", types, direction, num(len(s)), pct(len(s) / n_tx * 100),
                     eur(abs(amt.sum())), eur2(amt.abs().median()), eur2(amt.abs().max()),
                     pct(cust_share[cat]), f"{per_cust_month:.1f}",
                     num(int(s["merchant_id"].nunique())), num(int(s["mcc_code"].nunique()))])
    rows.sort(key=lambda r: -int(r[3].replace(" ", "")))
    w(table(["Category", "Transaction type", "Direction", "Rows", "Share", "Total", "Median amount",
             "Largest", "Customers with any", "Per customer per month", "Merchants", "MCC codes"], rows))
    w("\n\"Per customer per month\" counts only customers who have that category.\n")

    # ---- transaction types --------------------------------------------------
    w("## Transaction types\n")
    rows = []
    for t, s in tx.groupby("transaction_type", observed=True):
        rows.append([f"`{t}`", ", ".join(s["category"].unique().astype(str)), num(len(s)),
                     "out" if (s.tx_amount_eur < 0).all() else "in" if (s.tx_amount_eur > 0).all() else "mixed",
                     "yes" if s["mcc_code"].notna().any() else "no"])
    w(table(["Type", "Categories", "Rows", "Direction", "Has merchant / MCC"], rows))
    w("\nEach category has exactly one transaction type, so category and type say the same thing at different "
      "levels: `purchase` is every card purchase, the other types are bills, income and money movements.\n")

    # ---- MCC per category ---------------------------------------------------
    w("## Merchant types (MCC) per category\n")
    w("Only card purchases have an MCC. Rows without one in a purchase category are listed as *no MCC*.\n")
    for cat in tx.loc[tx.transaction_type == "purchase", "category"].value_counts().index:
        s = tx[tx.category == cat]
        rows = []
        for mcc, m in s.groupby(s["mcc_code"].fillna("—"), observed=True):
            label = MCC_LABELS.get(mcc, "no MCC" if mcc == "—" else "unknown")
            rows.append([f"`{mcc}`", label, num(len(m)), pct(len(m) / len(s) * 100),
                         eur2(m.tx_amount_eur.abs().median()), eur2(m.tx_amount_eur.abs().max()),
                         num(int(m["merchant_id"].nunique())), pct(m.customer_id.nunique() / n_cust * 100)])
        rows.sort(key=lambda r: -int(r[2].replace(" ", "")))
        w(f"### {cat}\n")
        w(table(["MCC", "Merchant type", "Rows", "Share of category", "Median", "Largest", "Merchants",
                 "Customers with any"], rows))
        w("")

    # ---- merchants ----------------------------------------------------------
    w("## Merchant IDs\n")
    m = tx["merchant_id"].dropna()
    prefixes = m.str.extract(r"^(MRC-[A-Z]+)-")[0]
    rows = []
    for p, s in tx.loc[m.index].groupby(prefixes, observed=True):
        rows.append([f"`{p}-…`", ", ".join(s["category"].unique().astype(str)), num(int(s.merchant_id.nunique())),
                     num(len(s))])
    w(table(["Prefix", "Category", "Merchants", "Rows"], rows))
    w(f"\nMerchant IDs are synthetic (`MRC-GRO-0035`): {num(int(m.nunique()))} merchants, no names or locations. "
      "They show *repeat visits to the same place*, not who the merchant is.\n")

    # ---- large one-off purchases --------------------------------------------
    w("## Large one-off purchases\n")
    p = tx[tx.transaction_type == "purchase"]
    spent = -p.tx_amount_eur
    ratio = spent / spent.groupby(p.category, observed=True).transform("median")
    rows = []
    for k in (10, 20, 50):
        s = p[ratio >= k]
        rows.append([f"≥ {k}× the category's median", num(len(s)), pct(len(s) / len(p) * 100),
                     num(int(s.customer_id.nunique()))])
    w(table(["Purchase size", "Rows", "Share of purchases", "Customers"], rows))
    w("")
    q99 = spent.groupby(p.category, observed=True).quantile([.99, .999]).unstack()
    big = p[ratio >= 20].groupby("category", observed=True).size()
    w(table(["Category", "99% of purchases are below", "99.9% are below", "Purchases ≥ 20× median"],
            [[c, eur(q99.loc[c, .99]), eur(q99.loc[c, .999]), num(int(big.get(c, 0)))] for c in q99.index]))
    w("\nRare but present in every category: candidates for the \"unexpected\" basket or for coaching "
      "(\"this one purchase was 40× your usual restaurant bill\").\n")

    # ---- timing of regular flows --------------------------------------------
    w("## Timing of regular payments and income\n")
    w("Day of month when each recurring flow usually happens. Useful for safe-to-spend: what is still due "
      "before the next salary.\n")
    rows = []
    for cat in ["Salary", "Housing", "Utilities", "Salary Sweep", "Invest Deposit", "Other Income"]:
        s = tx[tx.category == cat]
        if s.empty:
            continue
        days = s.tx_date.dt.day
        per_month = s.groupby(["customer_id", "month"], observed=True).size()
        rows.append([cat, f"{days.quantile(.1):.0f}–{days.quantile(.9):.0f}", f"{days.median():.0f}",
                     f"{per_month.median():.0f} (max {per_month.max()})",
                     pct(s.customer_id.nunique() / n_cust * 100)])
    w(table(["Flow", "Day of month (10–90%)", "Median day", "Per customer per month", "Customers"], rows))
    w("")

    # ---- income and spending per customer ------------------------------------
    w("## Per-customer monthly picture\n")
    spend_types = ["purchase", "housing_payment", "utilities_payment"]
    full_months = tx[(tx.tx_date >= first.replace(day=1) + pd.offsets.MonthBegin(1)) &
                     (tx.tx_date <= last)]
    n_full = full_months["month"].nunique()
    monthly = full_months.assign(
        income=full_months.tx_amount_eur.where(full_months.category.isin(["Salary", "Other Income"]), 0),
        spent=-full_months.tx_amount_eur.where(full_months.transaction_type.isin(spend_types), 0),
    ).groupby("customer_id", observed=True)[["income", "spent"]].sum() / n_full
    monthly["rate"] = (monthly.income - monthly.spent) / monthly.income.where(monthly.income > 0) * 100
    q = lambda s: [eur(s.quantile(x)) for x in (.1, .25, .5, .75, .9)]
    w(f"Averages over {n_full} complete months per customer. Spending = purchases, housing and utilities.\n")
    w(table(["", "10%", "25%", "Median", "75%", "90%"], [
        ["Monthly income (salary + other)"] + q(monthly.income),
        ["Monthly spending"] + q(monthly.spent),
        ["Income left after spending (% of income)"] + [pct(monthly.rate.quantile(x)) for x in (.1, .25, .5, .75, .9)],
    ]))
    w("")

    # ---- balances -----------------------------------------------------------
    w("## Balances\n")
    lows = tx.groupby("customer_id", observed=True)["balance_after_eur"].min()
    latest = tx.sort_values("tx_timestamp").groupby("customer_id", observed=True)["balance_after_eur"].last()
    w(table(["", "10%", "Median", "90%", "Min", "Max"], [
        ["Latest balance"] + [eur(latest.quantile(x)) for x in (.1, .5, .9)] + [eur(latest.min()), eur(latest.max())],
        ["Lowest balance ever"] + [eur(lows.quantile(x)) for x in (.1, .5, .9)] + [eur(lows.min()), eur(lows.max())],
    ]))
    w(f"\nCustomers whose balance ever went negative: {num(int((lows < 0).sum()))} "
      f"({pct((lows < 0).mean() * 100)}).\n")

    # ---- customers ----------------------------------------------------------
    w("## Customers\n")
    ages = customers["customer_age"]
    bins = [17, 24, 34, 44, 54, 64, 120]
    labels = ["18–24", "25–34", "35–44", "45–54", "55–64", "65+"]
    groups = pd.cut(ages, bins=bins, labels=labels).value_counts().reindex(labels)
    w(f"Ages {ages.min()}–{ages.max()}, median {ages.median():.0f}.\n")
    w(table(["Age group", "Customers", "Share"], [[k, num(int(v)), pct(v / len(customers) * 100)]
                                                   for k, v in groups.items()]))
    pc = customers["customer_postal_code"]
    areas = pc.str[:2].value_counts()
    w(f"\nPostal codes: {num(int(pc.nunique()))} unique; first two digits (area): "
      + ", ".join(f"`{a}xxx` {num(int(n))}" for a, n in areas.head(10).items())
      + (f", {len(areas) - 10} more areas" if len(areas) > 10 else "") + ".\n")

    # ---- mortgages ----------------------------------------------------------
    w("## Mortgage data\n")
    w(f"{num(len(outcomes))} mortgage applications ({num(int(outcomes.customer_id.nunique()))} customers), "
      f"{num(len(events))} events from {events['timestamp'].min()} to {events['timestamp'].max()}.\n")
    w("### Final outcomes\n")
    rows = [[f"`{k}`", num(int(v))] for k, v in outcomes["final_decision"].value_counts(dropna=False).items()]
    w(table(["final_decision", "Applications"], rows))
    rr = outcomes["rejection_reason"].value_counts()
    if len(rr):
        w("")
        w(table(["rejection_reason", "Applications"], [[r, num(int(n))] for r, n in rr.items()]))
    w("")
    w("### Event fields\n")
    for col in ["event_type", "property_type", "collateral_type", "collateral_status", "decision",
                "rejection_reason", "expense_type"]:
        vc = events[col].value_counts()
        w(f"**`{col}`** ({num(int(events[col].notna().sum()))} rows filled): "
          + ", ".join(f"`{k}` {num(int(v))}" for k, v in vc.items()) + "\n")
    rows = []
    for col in ["property_price_estimate", "loan_amount", "equity_amount", "collateral_value", "expense_amount"]:
        s = events[col].dropna()
        rows.append([f"`{col}`", num(len(s)), eur(s.min()), eur(s.median()), eur(s.max())])
    w(table(["Amount field", "Rows filled", "Min", "Median", "Max"], rows))
    w("")

    # ---- key findings (inserted after the intro) ------------------------------
    sweep_share = tx[tx.category == "Salary Sweep"].customer_id.nunique() / n_cust * 100
    findings = [
        "## Key findings for the coach\n",
        f"- **Every category has exactly one transaction type** and the {num(int(tx.mcc_code.nunique()))} "
        "merchant codes split the 8 card-purchase categories into finer merchant types (e.g. Transportation → "
        "fuel, parking, public transport, taxis). That is the finest level we can classify at: there are no "
        "merchant names, locations or free-text descriptions.",
        "- **Amounts don't differ by merchant type within a category**: e.g. every Transportation merchant type "
        "has a median of about 41 €, so a taxi costs the same as a tank of fuel. The data is synthetic; merchant "
        "types are useful as labels and for counting visits, not for telling expensive from cheap habits.",
        f"- **Large one-off purchases exist in every category** ({pct((ratio >= 20).mean() * 100)} of purchases "
        "are 20× their category's median). They are the natural content for the 🔧 unexpected basket and for "
        "\"what happened this month?\" explanations.",
        "- **Regular rhythm:** salary arrives once a month, usually from the 15th; housing is paid once a month "
        "in the first week; utilities about 3 times a month. Safe-to-spend can count what is still due before "
        "the next salary.",
        f"- **Money is tight for many customers:** median income left after spending is "
        f"{pct(monthly.rate.median())}, a quarter of customers keep {pct(monthly.rate.quantile(.25))} or less, "
        f"and {pct((lows < 0).mean() * 100)} have been overdrawn at some point. Safe-to-spend matters.",
        f"- **Salary sweeps affect only {pct(sweep_share)} of customers**, but for them most of the salary "
        "leaves the account, so their regular costs may be paid elsewhere.",
        f"- **Customers are mostly 35–54** and all live in the Helsinki region (postal areas 00, 01, 02). "
        f"Young adults (18–24), whom S-Bank highlights, are {pct(groups['18–24'] / len(customers) * 100)}.",
        f"- **Mortgage data covers only {num(len(outcomes))} customers** (April–May 2026): usable for a "
        "\"could I afford a home?\" feature, not for the core coach.",
        "",
    ]
    out[3:3] = findings

    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
