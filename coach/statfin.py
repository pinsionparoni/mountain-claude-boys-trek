"""
Statistics Finland's open benchmark: what Finnish households spend per month per
consumption unit, by age (coach/statfin_data.py, generated by scripts/fetch_statfin.py).

Only categories that map cleanly onto ours have a figure (Groceries, Restaurants,
Transportation, Health, Entertainment); everything else returns None, and the coach
says nothing about Finland for it.
"""

from coach.statfin_data import SOURCE, SPENDING_PER_MONTH


def monthly(category: str, age_group: str) -> float | None:
    """Average monthly spending in Finland for one of our age groups ("18–24") or "all"."""
    return SPENDING_PER_MONTH.get(age_group, {}).get(category)


def source() -> dict:
    """What the coach and the app say about where the figures come from."""
    return {
        "publisher": SOURCE["publisher"],
        "licence": SOURCE["licence"],
        "survey_year": SOURCE["survey_year"],
        "measure": SOURCE["measure"],
        "price_level": SOURCE["price_level"].split(" (")[0],
    }
